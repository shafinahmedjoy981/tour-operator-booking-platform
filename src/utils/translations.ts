/**
 * Universal translator function with fallback to English
 * Supports dot-notation: t('today.commissionSavedTitle')
 * Supports param substitution: t('today.guestsWaiting', { count: 5 })
 */
export function getTranslation(
  lang: Language,
  path: string,
  params?: Record<string, string | number>
): string {
  const keys = path.split('.');

  // 1. Try finding in requested language
  let current: any = translations[lang];
  let found = true;
  for (const k of keys) {
    if (current && typeof current === 'object' && k in current) {
      current = current[k];
    } else {
      found = false;
      break;
    }
  }

  // 2. If not found and language is not English, fall back to English
  if (!found || typeof current !== 'string') {
    current = translations.en;
    found = true;
    for (const k of keys) {
      if (current && typeof current === 'object' && k in current) {
        current = current[k];
      } else {
        found = false;
        break;
      }
    }
  }

  // 3. If still not found, return the key path
  if (!found || typeof current !== 'string') {
    return path;
  }

  let result = current;

  // 4. Substitute parameters like {count}, {name}
  if (params) {
    Object.entries(params).forEach(([paramKey, paramVal]) => {
      const regex = new RegExp(`\\{${paramKey}\\}`, 'g');
      result = result.replace(regex, String(paramVal));
    });
  }

  return result;
}

